import assert from 'node:assert/strict';
import {createWorker} from '../worker/auth.mjs';
const env={AUTH_USERNAME:'test-user',AUTH_PASSWORD:'test-only-password',SESSION_SECRET:crypto.randomUUID()};
const worker=createWorker({'/':{type:'text/html',data:btoa('protected dashboard')},'/assets/data.js':{type:'text/javascript',data:btoa('protected data')}},'login form');
const req=(url,options={})=>new Request('https://example.test'+url,options);
assert.equal((await worker.fetch(req('/'),env)).status,303);
assert.equal((await worker.fetch(req('/assets/data.js'),env)).status,401);
assert.equal(await (await worker.fetch(req('/login'),env)).text(),'login form');
const login=(username,password,origin='https://example.test')=>worker.fetch(req('/auth/login',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({username,password})}),env);
assert.equal((await login('test-user','wrong')).status,401);
assert.equal((await login('test-user','test-only-password','https://attacker.test')).status,403);
const response=await login(env.AUTH_USERNAME,env.AUTH_PASSWORD);assert.equal(response.status,200);
const setCookie=response.headers.get('set-cookie');assert.match(setCookie,/HttpOnly; Secure; SameSite=Strict/);
const cookie=setCookie.split(';')[0];
assert.equal(await (await worker.fetch(req('/',{headers:{Cookie:cookie}}),env)).text(),'protected dashboard');
assert.equal((await worker.fetch(req('/assets/data.js',{headers:{Cookie:cookie}}),env)).status,200);
assert.equal((await worker.fetch(req('/assets/data.js',{headers:{Cookie:cookie+'bad'}}),env)).status,401);
assert.equal((await worker.fetch(req('/',{headers:{Cookie:cookie}}),{...env,SESSION_SECRET:'rotated'})).status,303);
const logout=await worker.fetch(req('/auth/logout',{method:'POST',headers:{Origin:'https://example.test',Cookie:cookie}}),env);assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
assert.equal((await worker.fetch(req('/'),{})).status,503);
for(let i=0;i<5;i++)await login('test-user','wrong');assert.equal((await login('test-user','wrong')).status,429);
console.log('Auth checks passed: login, protected assets, cookie tampering, origin checks, logout, secret rotation and throttling.');
